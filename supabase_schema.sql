-- 1. Create Branches Table
CREATE TABLE IF NOT EXISTS public.branches (
    id TEXT PRIMARY KEY,
    branch_num TEXT NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    landmark TEXT,
    phone TEXT NOT NULL,
    tagline TEXT,
    hours TEXT NOT NULL,
    map_query TEXT,
    specialties JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Products Table
CREATE TABLE IF NOT EXISTS public.products (
    id TEXT PRIMARY KEY,
    category TEXT NOT NULL,       -- 'mobiles', 'accessories', 'spare_parts'
    subcategory TEXT,
    title TEXT NOT NULL,
    condition TEXT,
    battery_health TEXT,
    storage TEXT,
    color TEXT,
    price INTEGER NOT NULL,
    original_price INTEGER,
    warranty TEXT,
    image TEXT,
    specs JSONB DEFAULT '[]'::jsonb,
    badge TEXT,
    in_stock INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_email TEXT,
    delivery_type TEXT NOT NULL,  -- 'store_pickup' or 'home_delivery'
    address TEXT,
    branch_pickup TEXT,
    payment_method TEXT NOT NULL, -- 'cod_upi', 'store_pay', 'upi_online'
    total_amount INTEGER NOT NULL,
    status TEXT DEFAULT 'Confirmed',
    items_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Inquiries Table
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    model TEXT NOT NULL,
    service TEXT NOT NULL,
    branch TEXT NOT NULL,
    status TEXT DEFAULT 'New',    -- 'New', 'Contacted', 'Completed'
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for lightning fast queries
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_orders_created ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_inquiries_created ON public.inquiries(created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;

-- Allow Public Read Access for Storefront
CREATE POLICY "Public Read Branches" ON public.branches FOR SELECT USING (true);
CREATE POLICY "Public Read Products" ON public.products FOR SELECT USING (true);

-- Allow Public Insert for Orders and Inquiries
CREATE POLICY "Public Insert Orders" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Public Insert Inquiries" ON public.inquiries FOR INSERT WITH CHECK (true);

-- Service Role / Admin Access Policies
CREATE POLICY "Admin All Branches" ON public.branches FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin All Products" ON public.products FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin All Orders" ON public.orders FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Admin All Inquiries" ON public.inquiries FOR ALL USING (true) WITH CHECK (true);

